@Serializable
data class Workout(
    val id: String,
    val date: String,
    val type: WorkoutType,
    val title: String,
    val description: String,
    val steps: List<Step> = emptyList(),
    val plannedDistanceM: Int = 0,
    val plannedDurationS: Int = 0,
) {
    val localDate: LocalDate get() = LocalDate.parse(date)
}

@Serializable
enum class Phase(val title: String) {
    BASE("Base"), BUILD("Build"), PEAK("Peak"), TAPER("Taper"), RACE("Race week")
}

@Serializable
data class PlanWeek(
    val index: Int,
    val startDate: String,
    val phase: Phase,
    val focus: String,
    val workouts: List<Workout>,
) {
    val plannedDistanceM: Int get() = workouts.sumOf { it.plannedDistanceM }
}

@Serializable
data class TrainingPlan(
    val method: TrainingMethod,
    val createdDate: String,
    val raceDate: String,
    val paces: Paces,
    val weeks: List<PlanWeek>,
) {
    fun workoutOn(date: LocalDate): Workout? {
        val d = date.toString()
        for (w in weeks) for (x in w.workouts) if (x.date == d) return x
        return null
    }

    fun allWorkouts(): List<Workout> = weeks.flatMap { it.workouts }

    fun weekOf(date: LocalDate): PlanWeek? = weeks.lastOrNull { !LocalDate.parse(it.startDate).isAfter(date) }
        ?.takeIf { date.isBefore(LocalDate.parse(it.startDate).plusDays(7)) }
}

