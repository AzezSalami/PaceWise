/** A recording point. Taken every few seconds while the run is active. */
@Serializable
data class Sample(
    /** active seconds since start */
    val t: Int,
    /** cumulative metres */
    val d: Float,
    val hr: Int? = null,
    /** smoothed pace in s/km */
    val pace: Float? = null,
    val lat: Double? = null,
    val lon: Double? = null,
    val alt: Float? = null,
    val cad: Int? = null,
)

@Serializable
data class Split(val index: Int, val distanceM: Int, val durationS: Int, val avgHr: Int? = null)

@Serializable
data class StepResult(
    val label: String,
    val kind: StepKind,
    val distanceM: Int,
    val durationS: Int,
    val avgHr: Int? = null,
    val target: Target? = null,
)

@Serializable
enum class RunSource { WATCH, MANUAL }

@Serializable
data class RunRecord(
    val id: String,
    val startEpochMs: Long,
    /** active (moving) time */
    val durationS: Int,
    val elapsedS: Int = durationS,
    val distanceM: Int,
    val avgHr: Int? = null,
    val maxHr: Int? = null,
    val calories: Int? = null,
    val elevGainM: Int? = null,
    val avgCadence: Int? = null,
    val steps: Int? = null,
    val workoutId: String? = null,
    val title: String = "Run",
    val type: WorkoutType = WorkoutType.FREE,
    val source: RunSource = RunSource.WATCH,
    /** share of coached time spent inside the target, 0–100 */
    val onTargetPct: Int? = null,
    val splits: List<Split> = emptyList(),
    val stepResults: List<StepResult> = emptyList(),
    val samples: List<Sample> = emptyList(),
) {
    val localDate: LocalDate
        get() = Instant.ofEpochMilli(startEpochMs).atZone(ZoneId.systemDefault()).toLocalDate()
    val avgPace: Double? get() = if (distanceM > 50) durationS / (distanceM / 1000.0) else null
    fun summary(): RunRecord = if (samples.isEmpty()) this else copy(samples = emptyList())
}

