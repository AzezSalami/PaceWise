@Serializable
data class Profile(
    val method: TrainingMethod = TrainingMethod.CLASSIC,
    /** ISO date, e.g. 2027-04-25 */
    val raceDate: String,
    val raceName: String = "My marathon",
    val goalTimeS: Int = 4 * 3600,
    val level: Level = Level.BEGINNER,
    val daysPerWeek: Int = 4,
    /** ISO day of week, 1 = Monday … 7 = Sunday */
    val longRunDay: Int = 7,
    val planWeeks: Int = 18,
    val age: Int = 35,
    /** Measured maximum heart rate, if the runner knows it. */
    val maxHr: Int? = null,
    val units: Units = Units.KM,
) {
    val effectiveDays: Int get() = daysPerWeek.coerceIn(method.minDays, method.maxDays)
}

/** Pace band in seconds per kilometre. [fast] is the smaller number. */
@Serializable
data class PaceRange(val fast: Int, val slow: Int) {
    val mid: Int get() = (fast + slow) / 2
}

/** What the watch should hold the runner to during a step. Any part may be absent. */
@Serializable
data class Target(
    val paceFast: Int? = null,
    val paceSlow: Int? = null,
    val hrMin: Int? = null,
    val hrMax: Int? = null,
) {
    val hasPace: Boolean get() = paceFast != null && paceSlow != null
    val hasHr: Boolean get() = hrMax != null
}

@Serializable
enum class StepKind { WARMUP, RUN, RECOVER, COOLDOWN }

@Serializable
data class RunWalk(val runS: Int, val walkS: Int)

/** One block of a workout. Exactly one of [distanceM] / [durationS] is set. */
