    EASY("Easy run"),
    RECOVERY("Recovery run"),
    LONG("Long run"),
    MEDIUM_LONG("Medium-long run"),
    TEMPO("Tempo run"),
    MARATHON_PACE("Marathon pace"),
    INTERVALS("Intervals"),
    HILLS("Hills"),
    TEST("Fitness test"),
    RACE("Race day"),
    CROSS_TRAIN("Cross-training", isRun = false),
    FREE("Free run"),
